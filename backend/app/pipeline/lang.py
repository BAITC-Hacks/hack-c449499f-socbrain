"""Язык реплики по её тексту: ru | kk | mixed (шала-казахский) | "".

Спрашивать язык у движка распознавания мало: Whisper называет один язык на
фрагмент, а в смешанной речи внутри фразы бывают оба («біз договор не можем
подписать»). Честный источник — сами слова. Логика перенесена из aster_zapis
(server/internal/worker/lang.go), где проверена на живых разговорах.
"""
import re
from collections import Counter

RU, KK, MIXED, UNKNOWN = "ru", "kk", "mixed", ""
TITLES = {RU: "русский", KK: "казахский", MIXED: "смешанный", UNKNOWN: "не определён"}

# Буквы, которых нет в русском алфавите: движок не выдаёт их случайно.
KAZ_LETTERS = set("әғқңөұүһі")

# Казахские служебные слова — для реплик, где специфические буквы не попались.
KAZ_WORDS = {
    "бар", "жоқ", "жок", "және", "сіз", "сиз", "біз", "биз", "бұл", "деп", "ғой", "керек", "болады", "емес",
    "қалай", "қашан", "неге", "үшін", "туралы", "менің", "сіздің", "қазір", "рахмет", "жақсы", "иә", "мына",
    "сол", "осы", "енді", "ғана", "тағы",
}

# Русские служебные слова. Заимствований («договор», «заявка») нет намеренно:
# они звучат и в казахской речи, и по ним любая фраза выглядела бы смешанной.
# «он» не входит: по-казахски это «десять».
RUS_WORDS = {
    "что", "это", "как", "если", "потому", "меня", "вас", "нас", "вам", "нам", "который", "которые", "чтобы",
    "уже", "ещё", "еще", "очень", "пожалуйста", "спасибо", "хорошо", "сейчас", "может", "надо", "нужно",
    "будет", "было", "есть", "нет", "не", "они", "тогда", "просто", "там", "здесь", "почему", "когда",
    "сделать", "мы", "вы", "мне", "можем", "можно", "нельзя", "могу", "давайте", "были", "будем", "нужен",
    "нужна", "этот", "эта", "эти", "того", "так", "по", "на", "в", "и", "с", "у", "же", "вот", "до", "за",
}

WORD = re.compile(r"[a-zа-яёәғқңөұүһі]+")


def detect(text: str) -> str:
    words = WORD.findall(text.lower())
    if len(words) < 3:
        return UNKNOWN
    kaz = sum(1 for w in words if KAZ_LETTERS & set(w) or w in KAZ_WORDS)
    rus = sum(1 for w in words if w in RUS_WORDS)
    # Значим признак, который и повторился, и занимает заметную долю:
    # одно «рахмет» на прощание в русской речи — ещё не смена языка.
    kaz_ok = kaz >= 2 and kaz / len(words) >= 0.05
    rus_ok = rus >= 2 and rus / len(words) >= 0.05
    if kaz_ok and rus_ok:
        return MIXED
    if kaz_ok:
        return KK
    if rus_ok or not kaz:
        return RU
    return UNKNOWN


def meeting_language(utterances: list[dict]) -> str:
    """Язык совещания по длительности речи на каждом языке."""
    talk: Counter = Counter()
    for u in utterances:
        if u.get("lang"):
            talk[u["lang"]] += u["end"] - u["start"]
    if not talk:
        return UNKNOWN
    total = sum(talk.values())
    if talk[MIXED] / total >= 0.1 or (talk[KK] / total >= 0.1 and talk[RU] / total >= 0.1):
        return MIXED
    return talk.most_common(1)[0][0]
