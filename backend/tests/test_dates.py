"""Сроки из эталонных протоколов совещаний №1 и №2 (дата совещания — понедельник 21.09.2026)."""
import unittest
from datetime import date

from app.pipeline.dates import parse_deadline

BASE = date(2026, 9, 21)  # понедельник

CASES = [
    # совещание №1
    ("срок до 15 октября", date(2026, 10, 15)),
    ("до 26 сентября", date(2026, 9, 26)),
    ("срок к 20 октября", date(2026, 10, 20)),
    ("до пятницы", date(2026, 9, 25)),
    ("к пятнадцатому октября", date(2026, 10, 15)),
    ("на следующей неделе", date(2026, 10, 2)),
    ("на этой неделе", date(2026, 9, 25)),
    ("к среде", date(2026, 9, 23)),
    # совещание №2
    ("до конца недели", date(2026, 9, 25)),
    ("за две недели", date(2026, 10, 5)),
    ("Текущая неделя", date(2026, 9, 25)),
    ("1 неделя (смета)", date(2026, 9, 28)),
    ("за неделю", date(2026, 9, 28)),
    # прочие формы
    ("до конца квартала", date(2026, 9, 30)),
    ("к двадцать пятому сентября", date(2026, 9, 25)),
    ("пять рабочих дней", date(2026, 9, 28)),
    ("15.10", date(2026, 10, 15)),
    ("до 15 января", date(2027, 1, 15)),
    ("завтра", date(2026, 9, 22)),
    ("через месяц", date(2026, 10, 21)),
    # казахский
    ("жұмаға дейін", date(2026, 9, 25)),
    ("15 қазанға дейін", date(2026, 10, 15)),
    ("келесі аптада", date(2026, 10, 2)),
    ("екі апта ішінде", date(2026, 10, 5)),
    # не распознаётся — дата неизвестна
    ("После совещания с подрядчиками", None),
    ("Не указан", None),
    ("", None),
    ("к следующему совещанию", None),
]


class ParseDeadlineTest(unittest.TestCase):
    def test_cases(self):
        for text, expected in CASES:
            with self.subTest(text=text):
                self.assertEqual(parse_deadline(text, BASE), expected)

    def test_same_weekday_means_next_week(self):
        friday = date(2026, 9, 25)
        self.assertEqual(parse_deadline("до пятницы", friday), date(2026, 10, 2))


if __name__ == "__main__":
    unittest.main()
